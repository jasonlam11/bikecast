"""Rebalancing takeaway: which stations reliably drain or fill on weekday mornings.

Uses the best station-level model's forecasts (the global MLP) on the backtest weekdays, 7 to 10am,
and checks every claim against what actually happened. Thresholds were fixed before looking at
results. Writes reports/rebalancing.md, which the README quotes.

Limits: trip data shows flows, not inventory. Without dock counts or starting stock this is the
number of bikes the morning flow moves out of (or into) each station, not a truck schedule.
"""

import logging

import pandas as pd

from bikecast import config
from bikecast.evaluation.analysis import load_enriched_station_predictions, morning_net_flow
from bikecast.evaluation.metrics import mae, skill

log = logging.getLogger(__name__)

MODEL = "torch_mlp"
REFERENCE = "historical_average"
DRAIN_BELOW = -5.0  # bikes, net over 7 to 10am
FILL_ABOVE = 5.0
CONSISTENT_SHARE = 0.8  # share of weekday mornings
MIN_DAYS = 20  # stations open on fewer test weekdays are not classified
OUTPUT = config.REPORTS / "rebalancing.md"


def classify(flows: pd.DataFrame) -> pd.DataFrame:
    """Per station: how often the forecast drains or fills, and the same for actuals."""
    g = flows.groupby("station_id")
    t = pd.DataFrame(
        {
            "days": g.size(),
            "forecast_drain_share": g["forecast"].apply(lambda s: (s < DRAIN_BELOW).mean()),
            "forecast_fill_share": g["forecast"].apply(lambda s: (s > FILL_ABOVE).mean()),
            "actual_drain_share": g["actual"].apply(lambda s: (s < DRAIN_BELOW).mean()),
            "actual_fill_share": g["actual"].apply(lambda s: (s > FILL_ABOVE).mean()),
            "median_forecast": g["forecast"].median(),
            "median_actual": g["actual"].median(),
        }
    )
    eligible = t["days"] >= MIN_DAYS
    t["label"] = "mixed"
    t.loc[eligible & (t["forecast_drain_share"] >= CONSISTENT_SHARE), "label"] = "drains"
    t.loc[eligible & (t["forecast_fill_share"] >= CONSISTENT_SHARE), "label"] = "fills"
    t.loc[~eligible, "label"] = "too few days"
    return t


def summarize(flows: pd.DataFrame, t: pd.DataFrame) -> dict:
    out = {"weekdays": flows["date"].nunique()}
    for label, sign in [("drains", -1), ("fills", 1)]:
        ids = t.index[t["label"] == label]
        f = flows[flows["station_id"].isin(ids)]
        out[label] = {
            "stations": len(ids),
            "bikes_forecast": float(sign * t.loc[ids, "median_forecast"].sum()),
            "bikes_actual": float(sign * t.loc[ids, "median_actual"].sum()),
            # How often a flagged station really moved the way we said, on a given morning.
            "hit_rate": float(((f["actual"] * sign) > 0).mean()) if len(f) else float("nan"),
            "hit_rate_threshold": float(((f["actual"] * sign) > abs(DRAIN_BELOW)).mean())
            if len(f)
            else float("nan"),
        }
    return out


def write_report(
    t: pd.DataFrame, s: dict, names: pd.Series, ref: pd.DataFrame, skill_vs_ref: float
) -> str:
    d, f = s["drains"], s["fills"]
    lines = [
        "# Rebalancing takeaway",
        "",
        "_Generated by `src/bikecast/evaluation/rebalancing.py`. Do not edit by hand._",
        "",
        "## Summary",
        "",
        f"On a typical weekday morning (7 to 10am), **{d['stations']} of the 50 busiest stations "
        f"reliably drain**, losing a combined **{d['bikes_forecast']:.0f} bikes** by forecast "
        f"({d['bikes_actual']:.0f} actually), and **{f['stations']} reliably fill**, gaining a "
        f"combined **{f['bikes_forecast']:.0f} bikes** by forecast ({f['bikes_actual']:.0f} "
        "actually). "
        f"Restocking the draining stations before 7am, and clearing docks at the filling ones, "
        f"targets the flows that repeat every weekday.",
        "",
        f"On {d['hit_rate']:.0%} of mornings a station flagged as draining really did lose bikes "
        f"({d['hit_rate_threshold']:.0%} lost more than {abs(DRAIN_BELOW):.0f}). For filling "
        f"stations the rates are {f['hit_rate']:.0%} and {f['hit_rate_threshold']:.0%}.",
        "",
        "These morning patterns are very regular. The historical average baseline flags "
        f"{len(set(ref.index[ref['label'] == 'drains']) & set(t.index[t['label'] == 'drains']))} "
        f"of the same {d['stations']} draining stations and "
        f"{len(set(ref.index[ref['label'] == 'fills']) & set(t.index[t['label'] == 'fills']))} of "
        f"the same {f['stations']} filling stations, so the list itself does not need a learned "
        f"model. What the forecast adds is the day-specific amount, where the MLP is "
        f"{skill_vs_ref:.0%} more accurate than the historical average across all station-hours "
        "(results.md), with the biggest gains on holidays and rainy days.",
        "",
        "## Method",
        "",
        f"- Forecasts: the global MLP (`{MODEL}`), the best station-level model, on "
        f"{s['weekdays']} non-holiday weekdays across the 10 backtest weeks. Forecasts were made "
        "at midnight.",
        "- Morning net flow = forecast arrivals minus forecast departures, summed over 7, 8, and "
        "9am. Station-mornings with any closed hour are skipped.",
        f"- Drains: forecast net flow below {DRAIN_BELOW:+.0f} bikes on at least "
        f"{CONSISTENT_SHARE:.0%} of mornings. Fills: above {FILL_ABOVE:+.0f} on at least "
        f"{CONSISTENT_SHARE:.0%}. Stations open on fewer than {MIN_DAYS} test weekdays are not "
        "classified. Thresholds were set before looking at results.",
        "- Bikes to move = sum of each flagged station's median morning net flow. Actual values "
        "use the same stations and mornings.",
        "",
        "## Limits",
        "",
        "- Trip data shows flows, not inventory. Without dock counts or starting stock this is how "
        "many bikes the morning flow moves, not how many truck trips are needed.",
        "- Top 50 stations only, 10 test weeks, and forecast weather that is slightly better than "
        "a true next-day forecast.",
        "- The MLP is trained with L1 loss and forecasts the median, so it tends to under-count "
        "totals. The actual column shows by how much.",
        "",
    ]
    for label, title in [("drains", "Stations that drain"), ("fills", "Stations that fill")]:
        sub = t[t["label"] == label].sort_values("median_forecast", ascending=label == "drains")
        lines += [
            f"## {title}",
            "",
            "| station | name | weekdays | forecast share | actual share | median forecast | "
            "median actual |",
            "|---|---|---|---|---|---|---|",
        ]
        share = "drain_share" if label == "drains" else "fill_share"
        for sid, r in sub.iterrows():
            lines.append(
                f"| {sid} | {names.get(sid, sid)} | {r['days']} | {r[f'forecast_{share}']:.0%} | "
                f"{r[f'actual_{share}']:.0%} | {r['median_forecast']:+.1f} | "
                f"{r['median_actual']:+.1f} |"
            )
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    preds = load_enriched_station_predictions()
    flows = morning_net_flow(preds, MODEL)
    names = pd.read_parquet(config.PROCESSED / "stations.parquet").set_index("canonical_id")["name"]
    table = classify(flows)
    summary = summarize(flows, table)
    reference = classify(morning_net_flow(preds, REFERENCE))
    model_rows, ref_rows = preds[preds["model"] == MODEL], preds[preds["model"] == REFERENCE]
    model_mae = mae(model_rows["y"], model_rows["yhat"])
    ref_mae = mae(ref_rows["y"], ref_rows["yhat"])
    OUTPUT.write_text(write_report(table, summary, names, reference, skill(model_mae, ref_mae)))
    table.join(names).to_csv(config.REPORTS / "rebalancing_stations.csv")
    log.info("Wrote %s: %s", OUTPUT, summary)


if __name__ == "__main__":
    main()
